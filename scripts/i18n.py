#!/usr/bin/env python3
"""Localization check and generation.

Keys are the Simplified Chinese source strings. English lives in
Resources/en.lproj/Localizable.strings; the Chinese tables are generated as
identity maps so a Chinese system never falls back to the English table.

  i18n.py check            fail on unwrapped Chinese literals, missing or unused
                           English entries, or mismatched format specifiers
  i18n.py generate DIR     write zh-Hans/zh-Hant identity tables into DIR
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
english = root / "Resources/en.lproj/Localizable.strings"
han = re.compile(r"[一-鿿]")
literal = re.compile(r'"((?:[^"\\]|\\.)*)"')
entry = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;\s*$')
spec = re.compile(r"%(?:\d+\$)?[-+ 0#]*\d*(?:\.\d+)?(?:ll|l|h)?[@dDiuUxXoOfeEgGcCsSp%]")


def source_keys():
    keys, problems = set(), []
    for path in sorted((root / "Sources/MonitorLight").rglob("*.swift")):
        if path.name == "Localization.swift":
            continue
        for number, line in enumerate(path.read_text().splitlines(), 1):
            if line.strip().startswith("//"):
                continue
            for match in literal.finditer(line):
                text = match.group(1)
                if not han.search(text):
                    continue
                wrapped = line[max(0, match.start() - 2):match.start()] == "L("
                if wrapped or "// i18n-key" in line:
                    keys.add(text)
                    if text.startswith("低蓝光 · "):
                        keys.add(text.removeprefix("低蓝光 · "))
                else:
                    problems.append(f"{path.relative_to(root)}:{number}: unwrapped Chinese literal \"{text}\"")
    # The DDC helper reports errors and fallback names as keys; the app translates them.
    for line in (root / "Sources/DDCHelper/main.m").read_text().splitlines():
        for match in re.finditer(r'@"((?:[^"\\]|\\.)*)"', line):
            if han.search(match.group(1)):
                keys.add(match.group(1))
    return keys, problems


def read_table(path):
    table = {}
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip() or line.strip().startswith(("/*", "//", "*")):
            continue
        match = entry.match(line)
        if not match:
            raise SystemExit(f"{path}:{number}: malformed line: {line}")
        table[match.group(1)] = match.group(2)
    return table


def check():
    keys, problems = source_keys()
    table = read_table(english)
    for key in sorted(keys - table.keys()):
        problems.append(f"missing English translation: \"{key}\"")
    for key in sorted(table.keys() - keys):
        problems.append(f"unused English entry: \"{key}\"")
    for key, value in table.items():
        if sorted(spec.findall(key)) != sorted(spec.findall(value)):
            problems.append(f"format specifiers differ: \"{key}\" → \"{value}\"")
        if han.search(value):
            problems.append(f"English value contains Chinese: \"{key}\" → \"{value}\"")
    if problems:
        print("\n".join(problems))
        raise SystemExit(1)
    print(f"Localization check passed: {len(keys)} strings, all translated to English, format specifiers match")


def generate(directory):
    table = read_table(english)
    body = "/* Generated by scripts/i18n.py: keys are the Chinese source text. */\n" + "".join(
        f'"{key}" = "{key}";\n' for key in sorted(table))
    for language in ("zh-Hans", "zh-Hant"):
        target = Path(directory) / f"{language}.lproj"
        target.mkdir(parents=True, exist_ok=True)
        (target / "Localizable.strings").write_text(body)


if __name__ == "__main__":
    if sys.argv[1:] == ["check"]:
        check()
    elif len(sys.argv) == 3 and sys.argv[1] == "generate":
        generate(sys.argv[2])
    else:
        raise SystemExit(__doc__)
